/**
 * Generates lib/type-icons.ts from partywhale/pokemon-type-icons — vector
 * recreations of the type icons used in BDSP / Legends: Arceus / Scarlet &
 * Violet. MIT licensed (c) 2022 James Watkins.
 *
 *   npm run build:type-icons
 *
 * Each source file is a coloured disc plus a white glyph, so we lift two things
 * from it: the glyph path (re-coloured with currentColor at render time) and
 * the disc's official type colour. Inlining them means no extra requests and
 * no runtime dependency on GitHub.
 */
import { writeFile } from "node:fs/promises";

const BASE =
  "https://raw.githubusercontent.com/partywhale/pokemon-type-icons/main/icons";

const TYPES = [
  "normal", "fire", "water", "electric", "grass", "ice",
  "fighting", "poison", "ground", "flying", "psychic", "bug",
  "rock", "ghost", "dragon", "dark", "steel", "fairy",
];

/** Pull the fill declared for a given class in the embedded <style> block. */
function classFill(svg, cls) {
  const m = svg.match(
    new RegExp(`\\.${cls}\\s*{[^}]*fill:\\s*(#[0-9a-fA-F]{3,8})`),
  );
  return m ? m[1].toLowerCase() : null;
}

/** Rough perceptual lightness of a #rgb / #rrggbb fill, 0-1. */
function lightness(hex) {
  let h = hex.replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * The disc is a <circle>; the glyph is the near-white <path>s drawn on top.
 * A few icons carry an extra tinted path for shading — dropped, since these
 * render as a single-colour glyph at pill size.
 */
function glyphPaths(svg, fillOf) {
  const all = [...svg.matchAll(/<path\b[^>]*class="([^"]+)"[^>]*\bd="([^"]+)"/g)].map(
    (m) => ({ cls: m[1].trim(), d: m[2] }),
  );
  const white = all.filter((p) => {
    const f = fillOf(p.cls);
    return f && lightness(f) > 0.85;
  });
  return (white.length ? white : all).map((p) => p.d);
}

async function main() {
  const entries = [];

  for (const type of TYPES) {
    const res = await fetch(`${BASE}/${type}.svg`);
    if (!res.ok) throw new Error(`${type}: HTTP ${res.status}`);
    const svg = await res.text();

    const fillOf = (cls) => classFill(svg, cls);

    const paths = glyphPaths(svg, fillOf);
    if (!paths.length) throw new Error(`${type}: no glyph path found`);

    // The background disc carries the official type colour — but which class
    // that is varies between files, so read it off the <circle> itself.
    const discClass = svg.match(/<circle\b[^>]*class="([^"]+)"/)?.[1]?.trim();
    const color = discClass ? fillOf(discClass) : null;
    if (!color) throw new Error(`${type}: no disc colour found`);

    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 256 256";
    entries.push({ type, color, viewBox, paths });
    console.log(`  ${type.padEnd(9)} ${color}  ${paths.length} path(s)`);
  }

  const body = `// GENERATED by scripts/build-type-icons.mjs — do not edit by hand.
//
// Icons from https://github.com/partywhale/pokemon-type-icons
// MIT License (c) 2022 James Watkins. Vector recreations of the type icons in
// Brilliant Diamond / Shining Pearl, Legends: Arceus, and Scarlet & Violet.

import type { PokemonType } from "./dex";

export interface TypeIconData {
  /** The type's official disc colour, lifted from the source artwork. */
  color: string;
  viewBox: string;
  paths: string[];
}

export const TYPE_ICONS: Record<PokemonType, TypeIconData> = {
${entries
  .map(
    (e) =>
      `  ${e.type}: {\n    color: "${e.color}",\n    viewBox: "${e.viewBox}",\n    paths: [\n${e.paths
        .map((p) => `      ${JSON.stringify(p)},`)
        .join("\n")}\n    ],\n  },`,
  )
  .join("\n")}
};
`;

  await writeFile("lib/type-icons.ts", body, "utf8");
  console.log(`\n${entries.length} icons written to lib/type-icons.ts`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
